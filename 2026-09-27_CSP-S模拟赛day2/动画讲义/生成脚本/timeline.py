def md():
    out = ['| 北京时间 | T+ | 发生了什么（引号里是你的原话） | 评价 |', '|---|---|---|---|']
    for r in T:
        if r[0] == '##':
            out.append('| **%s** | | | |' % r[1])
        else:
            a, b, c, d = r
            conv = lambda s: s.replace('<b>', '**').replace('</b>', '**').replace('<code>', '`').replace('</code>', '`').replace('&lt;', '<').replace('&gt;', '>').replace('&amp;', '&').replace('|', '\\|')
            out.append('| %s | %s | %s | %s |' % (conv(a), b, conv(c), conv(d)))
    return '\n'.join(out)


def html():
    out = ['<div class="tw"><table class="tlt"><tr><th>北京时间</th><th>T+</th><th>发生了什么（引号里是你的原话）</th><th>评价</th></tr>']
    for r in T:
        if r[0] == '##':
            out.append('<tr class="ph"><td colspan="4">%s</td></tr>' % r[1])
        else:
            a, b, c, d = r
            cls = ''
            if '✗' in d:
                cls = ' class="bad"'
            elif '✓✓' in d:
                cls = ' class="key"'
            out.append('<tr%s><td class="tm">%s</td><td class="tm">%s</td><td>%s</td><td>%s</td></tr>' % (cls, a, b, c, d))
    out.append('</table></div>')
    return '\n'.join(out)
